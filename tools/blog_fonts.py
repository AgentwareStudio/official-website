#!/usr/bin/env python3
"""Full Chinese and Japanese fonts for the blog, cut into unicode-range slices.

Blog posts come from the database, so the site's subset fonts (tools/fonts.py) cannot know their characters. Blog
pages add 'AW Sans SC Full' / 'AW Sans JP Full' after the subsets: the browser downloads only the slices holding
characters that a page uses and the subset lacks.

Usage:
  python3 tools/blog_fonts.py                 # write public/fonts/cjk/*.woff2 and src/blog/cjk-fonts.css
  python3 tools/blog_fonts.py --import-ranges SC.css JP.css
                                              # refresh tools/cjk_slices.json from Google Fonts CSS
Sources (google/fonts, OFL), the same faces and version as tools/fonts.py:
  ofl/notosanssc/NotoSansSC[wght].ttf, ofl/notosansjp/NotoSansJP[wght].ttf
Paths default to ../fontlab/; pass --sc/--jp to override. The slice ranges follow Google Fonts' character-frequency
slicing, so the common characters share a few small files.
"""
import argparse, hashlib, json, pathlib, re
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = pathlib.Path(__file__).resolve().parent.parent
LAB = ROOT.parent / 'fontlab'
RANGES = ROOT / 'tools/cjk_slices.json'
OUT = ROOT / 'public/fonts/cjk'
CSS = ROOT / 'src/blog/cjk-fonts.css'
FACES = {'sc': ('AW Sans SC Full', 'NotoSansSC[wght].ttf'), 'jp': ('AW Sans JP Full', 'NotoSansJP[wght].ttf')}


def parse_ranges(text):
    """Code points of a CSS unicode-range value: U+4E00, U+4E00-4E0F, U+4E0? (wildcards)."""
    points = set()
    for part in (p.strip() for p in text.split(',')):
        hex_ = part[2:]
        if '?' in hex_:
            lo, hi = int(hex_.replace('?', '0'), 16), int(hex_.replace('?', 'F'), 16)
        elif '-' in hex_:
            lo, hi = (int(x, 16) for x in hex_.split('-'))
        else:
            lo = hi = int(hex_, 16)
        points.update(range(lo, hi + 1))
    return points


def css_ranges(points):
    """Compact unicode-range value for a set of code points."""
    out, run = [], []
    for cp in sorted(points):
        if run and cp == run[-1] + 1:
            run.append(cp)
            continue
        if run:
            out.append(run)
        run = [cp]
    if run:
        out.append(run)
    return ','.join(f'U+{r[0]:X}' if len(r) == 1 else f'U+{r[0]:X}-{r[-1]:X}' for r in out)


def import_ranges(sc_css, jp_css):
    data = {}
    for key, path in (('sc', sc_css), ('jp', jp_css)):
        ranges = re.findall(r'unicode-range:\s*([^;]+);', pathlib.Path(path).read_text(encoding='utf-8'))
        data[key] = [r.strip() for r in ranges]
    RANGES.write_text(json.dumps(data, indent=1) + '\n', encoding='utf-8')
    print(f"{RANGES.relative_to(ROOT)}: {len(data['sc'])} SC and {len(data['jp'])} JP slices")


def build(sources):
    slices = json.loads(RANGES.read_text(encoding='utf-8'))
    OUT.mkdir(parents=True, exist_ok=True)
    written, faces = set(), ['/* Generated by tools/blog_fonts.py; do not edit. Loaded by blog pages only (blog.css). */']
    for key, (family, _) in FACES.items():
        cmap = set(TTFont(sources[key], lazy=True).getBestCmap())
        total = 0
        for i, value in enumerate(slices[key]):
            points = parse_ranges(value) & cmap
            if not points:
                continue
            # No new timestamps: the same sources give the same files (and URLs).
            font = TTFont(sources[key], recalcTimestamp=False)
            o = subset.Options()
            o.layout_features = ['*']; o.name_IDs = ['*']; o.notdef_outline = True; o.hinting = False
            s = subset.Subsetter(o); s.populate(unicodes=sorted(points)); s.subset(font)
            font = instancer.instantiateVariableFont(font, {'wght': (300, 700)})
            font.flavor = 'woff2'
            tmp = OUT / f'.{key}-{i:03d}.tmp'
            font.save(tmp)
            body = tmp.read_bytes()
            name = f'{key}-{i:03d}.{hashlib.sha256(body).hexdigest()[:10]}.woff2'
            tmp.replace(OUT / name)
            written.add(name)
            total += len(body)
            faces.append(f"@font-face {{ font-family: '{family}'; src: url('/fonts/cjk/{name}') format('woff2'); "
                         f"font-weight: 300 700; font-display: swap; unicode-range: {css_ranges(points)}; }}")
        print(f'{family}: {sum(1 for n in written if n.startswith(key))} slices, {total // 1024} KB')
    for stale in OUT.glob('*.woff2'):
        if stale.name not in written:
            stale.unlink()
    CSS.write_text('\n'.join(faces) + '\n', encoding='utf-8')
    print(f'{CSS.relative_to(ROOT)}: {len(faces) - 1} @font-face rules')


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--sc', default=str(LAB / FACES['sc'][1]))
    ap.add_argument('--jp', default=str(LAB / FACES['jp'][1]))
    ap.add_argument('--import-ranges', nargs=2, metavar=('SC_CSS', 'JP_CSS'))
    a = ap.parse_args()
    if a.import_ranges:
        import_ranges(*a.import_ranges)
    else:
        build({'sc': a.sc, 'jp': a.jp})
