#!/usr/bin/env python3
"""Subset the CJK fonts (variable, OFL) to the characters each locale actually uses.

Usage:  python3 tools/fonts.py
Sources (google/fonts, OFL):
  ofl/notosanssc/NotoSansSC[wght].ttf  -> src/assets/fonts/aw-sans-sc.woff2  (zh-CN copy: src/**/*.ts(x) + zh HTML)
  ofl/notosansjp/NotoSansJP[wght].ttf  -> src/assets/fonts/aw-sans-jp.woff2  (src/i18n/locales/ja.json + ja HTML)
  ofl/notosanskr/NotoSansKR[wght].ttf  -> src/assets/fonts/aw-sans-kr.woff2  (src/i18n/locales/ko.json + ko HTML)
Paths default to ../fontlab/; pass --sc/--jp/--kr to override. Re-run after changing copy.
Latin locales use Inter and local system monospace fonts (Latin-1 coverage is enough for en/es/de/fr/pt).

Use --shared-only to rebuild cross-language subsets from the committed WOFF2 files,
without downloading the original TTFs. Generated CSS/assets are processed and hashed by Vite.
"""
import argparse, pathlib
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = pathlib.Path(__file__).resolve().parent.parent
LAB = ROOT.parent / 'fontlab'
PUNCT = set('“”‘’—–…→←↑↓↗≠·•›✓　，。、；：？！（）《》「」『』〜・')
SHARED_SOURCES = ['src/sections/Pages.tsx']
# FreeType's CJK auto-hinter samples these glyphs to align strokes. Removing them can
# change rasterization even when the displayed glyph outlines and advances are identical.
# Reference: https://github.com/freetype/freetype/blob/master/src/autofit/afblue.dat
# (AF_BLUE_STRING_CJK_*), and afscript.h (HANI standard characters).
HINTING_REFERENCE = set(
    '田囗他们你來們到和地对對就席我时時會来為能舰說说这這齊'
    '军同已愿既星是景民照现現理用置要軍那配里開雷露面顾'
    '个为人以個大有主些因它想意生當看着者自著裡过还进進過道還'
    '她将將年得情最样樣通即吗吧听呢品响嗎师師收断斷明眼間间际陈限除陳随際隨'
    '事前學或政斯新沒没然特球第經谁起例別别制动動增指朝期构物确种調调費费都'
)


def read(paths):
    s = set()
    for p in paths:
        if p.exists():
            s |= set(p.read_text(encoding='utf-8'))
    return s


def make(src, chars, out):
    cjk = {c for c in chars | PUNCT if ord(c) > 0x2000}
    font = TTFont(src)
    o = subset.Options()
    o.layout_features = ['*']; o.name_IDs = ['*']; o.notdef_outline = True; o.hinting = False
    s = subset.Subsetter(o); s.populate(unicodes=[ord(c) for c in cjk]); s.subset(font)
    font = instancer.instantiateVariableFont(font, {'wght': (300, 700)})
    font.flavor = 'woff2'
    dst = ROOT / 'src/assets/fonts' / out
    font.save(dst)
    print(f'{out}: {len(cjk)} chars, {dst.stat().st_size // 1024} KB')


def shared_subsets():
    """Keep native pages on the original face; only cross-language labels use these subsets.

    This avoids splitting native paragraphs across font faces (and changing kerning/shaping).
    Pages.tsx contains the cross-language course names and language labels.
    Inter still handles Latin text. The original CJK face remains a fallback for new characters
    until this generator is rerun.
    """
    chars = {ord(c) for p in SHARED_SOURCES for c in (ROOT / p).read_text(encoding='utf-8')}
    chars |= {ord(c) for c in HINTING_REFERENCE}
    dst = ROOT / 'src/fonts'
    dst.mkdir(exist_ok=True)
    css = ['/* Generated by tools/fonts.py --shared-only; do not edit. */']
    for suffix in ('sc', 'jp'):
        source = ROOT / f'src/assets/fonts/aw-sans-{suffix}.woff2'
        font = TTFont(source, recalcTimestamp=False, recalcBBoxes=False)
        unicodes = sorted(chars & font.getBestCmap().keys())
        options = subset.Options()
        options.layout_features = ['*']
        options.name_IDs = ['*']
        options.notdef_outline = True
        options.recalc_timestamp = False
        subsetter = subset.Subsetter(options)
        subsetter.populate(unicodes=unicodes)
        subsetter.subset(font)
        name = f'aw-sans-{suffix}-shared.woff2'
        font.save(dst / name)
        ranges = ','.join(f'U+{c:X}' for c in unicodes)
        css.append(
            f"@font-face {{ font-family: 'AW Sans {suffix.upper()} Shared'; "
            f"src: url('./{name}') format('woff2'); font-weight: 300 700; "
            f"font-display: swap; unicode-range: {ranges}; }}"
        )
        print(f'{name}: {len(unicodes)} characters, {(dst / name).stat().st_size} bytes')
    (dst / 'shared.css').write_text('\n'.join(css) + '\n', encoding='utf-8')


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--sc', default=str(LAB / 'NotoSansSC-VF.ttf'))
    ap.add_argument('--jp', default=str(LAB / 'dl' / 'NotoSansJP-VF.ttf'))
    ap.add_argument('--kr', default=str(LAB / 'dl' / 'NotoSansKR-VF.ttf'))
    ap.add_argument('--shared-only', action='store_true', help='Rebuild shared subsets from committed WOFF2s only')
    a = ap.parse_args()
    if not a.shared_only:
        zh_html = [*ROOT.glob('zh/**/index.html')]
        zh = read([*ROOT.glob('src/**/*.ts'), *ROOT.glob('src/**/*.tsx'), *zh_html])
        ja = read([ROOT / 'src/i18n/locales/ja.json', *ROOT.glob('ja/**/index.html'), ROOT / 'src/i18n.ts'])
        ko = read([ROOT / 'src/i18n/locales/ko.json', *ROOT.glob('ko/**/index.html'), ROOT / 'src/i18n.ts'])
        make(a.sc, zh, 'aw-sans-sc.woff2')
        make(a.jp, ja, 'aw-sans-jp.woff2')
        make(a.kr, {c for c in ko if not ('一' <= c <= '鿿')} | set('한국어'), 'aw-sans-kr.woff2')
    shared_subsets()
